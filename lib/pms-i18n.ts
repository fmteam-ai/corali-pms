export const pmsDictionaries: Record<PmsLang, Record<PmsKey, string>> = { el, en };

export type PmsTranslator = (key: PmsKey, vars?: Record<string, string | number>) => string;

export function pmsT(lang: PmsLang): PmsTranslator {
  const dictionary = pmsDictionaries[lang] ?? el;
  return (key, vars) => {
    const template = dictionary[key] ?? el[key] ?? key;
    return vars ? template.replace(/\{(\w+)\}/g, (_, name: string) => (vars[name] === undefined ? `{${name}}` : String(vars[name]))) : template;
  };
}

export function pmsLocale(lang: PmsLang): string {
  return lang === "en" ? "en-GB" : "el-GR";
}

/** Translate a known status code, falling back to the raw value for unknown codes. */
export function pmsStatus(lang: PmsLang, status: string): string {
  const key = `status.${status}` as PmsKey;
  return key in el ? pmsT(lang)(key) : status;
}
