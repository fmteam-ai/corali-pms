// v179: the set-up file for the hotel's Raspberry Pi bridge: a cloud-init «user-data» file that Raspberry Pi OS reads
// at its first start. It writes the bridge program, its config (PMS address + token) and a service that starts it
// at every boot. The hotel copies it onto the memory card after writing Raspberry Pi OS Lite with Raspberry Pi Imager.
import { readFile } from "node:fs/promises";
import path from "node:path";

const indent = (text: string, n: number) => text.split("\n").map((l) => (l ? " ".repeat(n) + l : l)).join("\n");

export async function bridgeUserData(pmsOrigin: string, token: string): Promise<string> {
  const program = await readFile(path.join(process.cwd(), "scripts", "corali_bridge.py"), "utf8");
  const config = JSON.stringify({ pms: pmsOrigin.replace(/\/$/, ""), token });
  const service = [
    "[Unit]",
    "Description=Corali PMS - Omada Wi-Fi bridge",
    "Wants=network-online.target",
    "After=network-online.target",
    "",
    "[Service]",
    "ExecStart=/usr/bin/python3 /opt/corali-bridge/corali_bridge.py",
    "Restart=always",
    "RestartSec=30",
    "",
    "[Install]",
    "WantedBy=multi-user.target",
    "",
  ].join("\n");
  return [
    "#cloud-config",
    "# Corali PMS - Omada Wi-Fi bridge (generated by the PMS; contains the bridge's key: keep it private).",
    "hostname: corali-bridge",
    "users:",
    "  - name: corali",
    "    groups: users",
    "    lock_passwd: true",
    "    shell: /bin/bash",
    "write_files:",
    "  - path: /etc/corali-bridge.json",
    "    permissions: '0600'",
    "    content: |",
    indent(config, 6),
    "  - path: /opt/corali-bridge/corali_bridge.py",
    "    permissions: '0755'",
    "    content: |",
    indent(program, 6),
    "  - path: /etc/systemd/system/corali-bridge.service",
    "    permissions: '0644'",
    "    content: |",
    indent(service, 6),
    "runcmd:",
    "  - [systemctl, daemon-reload]",
    "  - [systemctl, enable, --now, corali-bridge.service]",
    "",
  ].join("\n");
}
